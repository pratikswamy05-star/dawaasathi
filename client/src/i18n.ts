const DICTS: Record<Lang, Partial<Dict>> = { en, kn, hi };
export type TKey = keyof Dict;

export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>) {
  let s = DICTS[lang][key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function useT() {
  const lang = useAuth((s) => s.lang);
  return { lang, t: (key: TKey, vars?: Record<string, string | number>) => translate(lang, key, vars) };
}

